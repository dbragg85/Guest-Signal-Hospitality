create or replace function public.growth_operator_metrics(p_days integer default 7)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with bounds as (
    select
      now() - make_interval(days => greatest(1, least(coalesce(p_days, 7), 90))) as period_start,
      now() - interval '1 day' as day_start
  ),
  event_totals as (
    select
      count(*) filter (where occurred_at >= (select day_start from bounds))::int as events_24h,
      count(*)::int as events_period,
      count(distinct session_id) filter (
        where occurred_at >= (select day_start from bounds)
      )::int as sessions_24h,
      count(distinct session_id)::int as sessions_period,
      count(*) filter (where event_name = 'page_view')::int as page_views,
      count(*) filter (where event_name = 'cta_click')::int as cta_clicks,
      count(*) filter (where event_name = 'form_start')::int as form_starts,
      count(*) filter (
        where event_name in ('snapshot_intake_success', 'contact_submit_success')
      )::int as form_completions,
      count(*) filter (where event_name = 'portal_upgrade_click')::int as portal_upgrade_clicks
    from public.site_events
    where occurred_at >= (select period_start from bounds)
  ),
  sales as (
    select
      count(*) filter (where stage = 'new')::int as new_count,
      count(*) filter (where stage = 'qualified')::int as qualified_count,
      count(*) filter (where stage = 'meeting')::int as meeting_count,
      count(*) filter (where stage = 'proposal')::int as proposal_count,
      count(*) filter (where stage = 'won')::int as won_count,
      count(*) filter (where stage = 'lost')::int as lost_count,
      coalesce(sum(monthly_value_cents) filter (where stage = 'won'), 0)::int as mrr_cents,
      count(*) filter (
        where next_action_at <= now() and stage not in ('won', 'lost')
      )::int as follow_ups_due
    from public.sales_opportunities
    where is_test = false
  ),
  intake as (
    select
      count(*) filter (where processing_status = 'pending')::int as pending,
      count(*) filter (where processing_status = 'processing')::int as processing,
      count(*) filter (where processing_status = 'failed')::int as failed,
      count(*) filter (
        where created_at >= (select period_start from bounds)
      )::int as submissions_period
    from public.lead_intake_submissions li
    where not exists (
      select 1
      from public.sales_opportunities so
      where so.lead_intake_id = li.id and so.is_test = true
    )
  ),
  prospects as (
    select
      count(*) filter (where status = 'approval_required')::int as approval_required,
      count(*) filter (where status = 'approved')::int as approved,
      count(*) filter (where status = 'contacted')::int as contacted,
      count(*) filter (where status = 'replied')::int as replied
    from public.prospect_queue
  )
  select jsonb_build_object(
    'generated_at', now(),
    'days', greatest(1, least(coalesce(p_days, 7), 90)),
    'events', to_jsonb(event_totals),
    'sales', to_jsonb(sales),
    'intake', to_jsonb(intake),
    'prospects', to_jsonb(prospects)
  )
  from event_totals, sales, intake, prospects;
$$;

revoke all on function public.growth_operator_metrics(integer)
  from public, anon, authenticated;
grant execute on function public.growth_operator_metrics(integer) to service_role;
